def n6_storyboard(system: str, user: str) -> str:
    # 从成稿中提取段与正文行（mock 简化：每段一单元）
    script = user.split("## 输入：旁白成稿", 1)[-1].split("## 输入：大纲情绪坐标", 1)[0]
    pages = []
    cur = None
    for line in script.splitlines():
        m = re.match(r"^【段(\d+)[·・]([^】]+)】", line.strip())
        if m:
            cur = {"段号": int(m.group(1)), "对应成稿段": f"【段{m.group(1)}·{m.group(2)}】",
                   "文本": "", "拆分": [], "情感": "平稳放缓", "情感强度": 0.7,
                   "语速": 1.0, "前停顿_ms": 0, "后停顿_ms": 500,
                   "读音表": {"妺喜": "mò xǐ"} if "妺喜" in line else {},
                   "时长目标_s": None, "备注": ""}
            pages.append(cur)
        elif cur is not None and line.strip() and not line.startswith("#") and not line.startswith(">"):
            txt = re.sub(r"【上屏】[^\n]*", "", line).strip()
            txt = txt.replace("（顿）", "").strip()
            if txt:
                cur["拆分"].append(txt)
                cur["文本"] += txt
    for p in pages:
        if not p["拆分"]:
            p["拆分"] = [f"第{p['段号']}段正文。"]
            p["文本"] = p["拆分"][0]
        if "【段5" in p["对应成稿段"]:
            p["情感"] = "压低后的爆发，克制中带狠劲"
            p["情感强度"] = 0.8
        if "【段6" in p["对应成稿段"]:
            p["情感"] = "低沉克制，带唏嘘"
            p["后停顿_ms"] = 800
    return _j({"画本": pages, "新增读音": {"妺喜": "mò xǐ", "亳": "bó"}, "打回写作层条目": []})


