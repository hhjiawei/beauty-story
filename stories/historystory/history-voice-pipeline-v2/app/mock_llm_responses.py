def n4_chapter(system: str, user: str) -> str:
    # 从「本章施工段落」提取段号
    sec = user.split("本章施工段落", 1)[-1].split("## 输入：事件卡", 1)[0]
    seg_nos = [int(x) for x in re.findall(r'"段号"\s*:\s*(\d+)', sec)]
    if not seg_nos:
        seg_nos = [1]
    parts = []
    for n in seg_nos:
        func = _FUNC_NAMES.get(n, "主线·关键节点")
        body = _MOCK_LINES.get(n, f"第{n}段的正文。")
        parts.append(f"【段{n}·{func}】\n{body}")
    return _j({"本章正文": "\n\n".join(parts), "技法切换声明": [], "施工异议": []})


